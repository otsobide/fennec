//! Command for describing an autonomous system.

use shared_cqrs::command::domain::command::Command;

use crate::autonomous_system::domain::value_objects::autonomous_system_id::AutonomousSystemId;
use crate::autonomous_system::domain::value_objects::autonomous_system_name::AutonomousSystemName;
use crate::autonomous_system::domain::value_objects::autonomous_system_rir::AutonomousSystemRir;

/// Command that replaces the name and the registry of a registered
/// autonomous system; `None` clears a field.
///
/// The number is not part of the command: it is the identity and never
/// changes. `updated_at` is generated by [`AutonomousSystemUpdater`] at
/// execution time.
///
/// [`AutonomousSystemUpdater`]: super::autonomous_system_updater::AutonomousSystemUpdater
pub struct UpdateAutonomousSystemCommand {
    pub id: AutonomousSystemId,
    pub name: Option<AutonomousSystemName>,
    pub rir: Option<AutonomousSystemRir>,
}

impl Command for UpdateAutonomousSystemCommand {}
